def cost_function(X, Y, W):
    """
    Compute Mean Squared Error (MSE).
    X: (m, d) feature matrix
    Y: (m, 1) target vector
    W: (d, 1) weight matrix
    """
    m = X.shape[0]
    Y_pred = X.dot(W)  # (m, 1)
    cost = (1/(2*m)) * np.sum((Y_pred - Y) ** 2)
    return cost

