def gradient_descent(X, Y, W, alpha, iterations):
    cost_history = [0] * iterations
    m = len(Y)

    for i in range(iterations):
        Y_pred = np.dot(X, W)
        loss = Y_pred - Y
        dw = np.dot(X.T, loss) / m
        W = W - alpha * dw
        cost_history[i] = cost_function(X, Y, W)

    return W, cost_history

